import React, { useMemo, useState } from 'react';
import {
  Calendar,
  Check,
  CheckCircle2,
  Clock,
  Copy,
  Flame,
  Share2,
  Sparkles,
  TrendingUp,
} from 'lucide-react';
import type { BootstrapData } from '../api/client';
import { addDays, formatDateReadable } from '../utils/dateLogic';
import { buildDateRangeAnalytics } from '../utils/analyticsLogic';
import { GlassModal } from './GlassModal';

interface WeeklyReviewModalProps {
  open: boolean;
  onClose: () => void;
  data: BootstrapData;
}

export const WeeklyReviewModal: React.FC<WeeklyReviewModalProps> = ({
  open,
  onClose,
  data,
}) => {
  const [copied, setCopied] = useState(false);

  const review = useMemo(() => {
    const today = data.today;
    const startDate = addDays(today, -6);

    const past7Series = buildDateRangeAnalytics({
      endDate: today,
      daysCount: 7,
      routines: data.routines,
      routineOccurrences: data.routineOccurrences,
      tasks: data.tasks,
      studySessions: data.studySessions,
      workSessions: data.workSessions,
      focusSessions: data.focusSessions,
      habits: data.habits,
    });

    const totalTasksDone = past7Series.reduce((s, p) => s + p.tasksCompleted, 0);
    const totalTasksPlanned = past7Series.reduce((s, p) => s + p.tasksTotal, 0);
    const taskRate = totalTasksPlanned > 0 ? Math.round((totalTasksDone / totalTasksPlanned) * 100) : 100;

    const totalStudyMins = past7Series.reduce((s, p) => s + p.studyMinutes, 0);
    const totalWorkMins = past7Series.reduce((s, p) => s + p.workMinutes, 0);
    const totalFocusMins = past7Series.reduce((s, p) => s + p.focusMinutes, 0);
    const totalProductiveHours =
      Math.round(((totalStudyMins + totalWorkMins + totalFocusMins) / 60) * 10) / 10;

    const avgScore =
      past7Series.length > 0
        ? Math.round(past7Series.reduce((s, p) => s + p.score, 0) / past7Series.length)
        : 0;

    // AI summary recommendation
    let recommendation = '';
    if (avgScore >= 80) {
      recommendation = 'Outstanding week! Your consistency and focus were exceptional. Keep this rhythm and set higher milestone goals for next week.';
    } else if (avgScore >= 60) {
      recommendation = 'Solid progress! You maintained good focus. For next week, try scheduling your hardest tasks earlier in the morning to boost completion.';
    } else {
      recommendation = 'Room to grow. Start next week with smaller 25-minute Pomodoro focus blocks and reduce task overload.';
    }

    return {
      startDate,
      endDate: today,
      totalTasksDone,
      totalTasksPlanned,
      taskRate,
      totalProductiveHours,
      avgScore,
      recommendation,
      past7Series,
    };
  }, [data]);

  const handleCopy = async () => {
    const text = `📊 Raa's Diary — Weekly Review (${review.startDate} to ${review.endDate})
━━━━━━━━━━━━━━━━━━━━━━
🎯 Weekly Average Score: ${review.avgScore}%
✅ Total Tasks Done: ${review.totalTasksDone} / ${review.totalTasksPlanned} (${review.taskRate}%)
⏱️ Total Focus Hours: ${review.totalProductiveHours}h
💡 AI Recommendation: ${review.recommendation}
━━━━━━━━━━━━━━━━━━━━━━
Generated by Raa's Diary Life OS 🚀`;

    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // Fallback
    }
  };

  return (
    <GlassModal
      open={open}
      onClose={onClose}
      title="AI Weekly Review"
      subtitle={`${review.startDate} to ${review.endDate}`}
    >
      <div className="space-y-4">
        {/* Top summary banner */}
        <div className="p-4 rounded-2xl bg-gradient-to-r from-[var(--accent)]/15 to-[var(--accent-secondary)]/15 border border-[var(--glass-border)] flex items-center justify-between">
          <div>
            <div className="text-xs text-[var(--text-secondary)]">7-Day Average Score</div>
            <div className="text-3xl font-extrabold font-mono-num text-[var(--accent)] mt-0.5">
              {review.avgScore}%
            </div>
          </div>
          <div className="text-right">
            <div className="text-xs text-[var(--text-secondary)]">Total Focus Time</div>
            <div className="text-2xl font-bold font-mono-num text-[var(--success)] mt-0.5">
              {review.totalProductiveHours}h
            </div>
          </div>
        </div>

        {/* 7-Day Mini Sparkline Grid */}
        <div className="space-y-1.5">
          <div className="text-xs text-[var(--text-secondary)] font-medium">Daily Breakdown</div>
          <div className="grid grid-cols-7 gap-1.5">
            {review.past7Series.map((p) => (
              <div
                key={p.date}
                className="p-2 rounded-xl bg-white/[0.04] border border-[var(--glass-border-subtle)] text-center space-y-1"
              >
                <div className="text-[10px] text-[var(--text-muted)] font-mono-num">{p.label}</div>
                <div className="text-xs font-bold font-mono-num text-[var(--accent)]">{p.score}%</div>
              </div>
            ))}
          </div>
        </div>

        {/* AI Insight & Recommendations */}
        <div className="p-3.5 rounded-xl bg-[var(--accent)]/10 border border-[var(--accent)]/20 space-y-1.5">
          <div className="flex items-center gap-1.5 text-xs font-semibold text-[var(--accent)]">
            <Sparkles className="w-3.5 h-3.5" />
            <span>AURAA AI Strategic Insight</span>
          </div>
          <p className="text-xs text-[var(--text-secondary)] leading-relaxed">
            {review.recommendation}
          </p>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-2 pt-2">
          <button
            type="button"
            onClick={handleCopy}
            className="glass-button-primary flex-1 py-2.5 text-xs font-semibold flex items-center justify-center gap-2"
          >
            {copied ? (
              <>
                <Check className="w-4 h-4 text-emerald-300" />
                <span>Weekly Review Copied!</span>
              </>
            ) : (
              <>
                <Share2 className="w-4 h-4" />
                <span>Share Weekly Summary</span>
              </>
            )}
          </button>
          <button type="button" onClick={onClose} className="glass-button px-4 py-2.5 text-xs">
            Close
          </button>
        </div>
      </div>
    </GlassModal>
  );
};
